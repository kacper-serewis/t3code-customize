#!/usr/bin/env python3
"""Regenerate the Material Symbols icon shim for the T3 Code source checkout.

Usage: generate.py <source-checkout>

Reads map.txt (Lucide export name, Material Symbols name), downloads the Rounded
400 SVGs from the @material-symbols/svg-400 npm package and writes
apps/web/src/components/icons/materialSymbols.generated.tsx.
"""
import math
import re
import sys
import urllib.request
from pathlib import Path

VERSION = '0.49.0'
HERE = Path(__file__).resolve().parent
CACHE = HERE / '.cache' / VERSION
OUT = 'apps/web/src/components/icons/materialSymbols.generated.tsx'


def dashed_circle(dot=False, dashes=8, sweep=27, outer=400, inner=340):
    """Lucide's dashed circle at Material's stroke weight; Material Symbols has no such glyph."""
    cap = (outer - inner) / 2

    def at(radius, degrees):
        a = math.radians(degrees)
        return f'{480 + radius * math.sin(a):.0f} {-480 - radius * math.cos(a):.0f}'

    out = []
    for i in range(dashes):
        a0 = i * 360 / dashes - sweep / 2
        a1 = a0 + sweep
        out.append(f'M{at(outer, a0)}A{outer} {outer} 0 0 1 {at(outer, a1)}A{cap:.0f} {cap:.0f} 0 0 1 {at(inner, a1)}'
                   f'A{inner} {inner} 0 0 0 {at(inner, a0)}A{cap:.0f} {cap:.0f} 0 0 1 {at(outer, a0)}Z')
    if dot:
        out.append('M480 -550A70 70 0 1 1 480 -410A70 70 0 1 1 480 -550Z')
    return ''.join(out)


# Glyphs drawn here because Material Symbols has no equivalent. map.txt names them with a leading @.
CUSTOM = {'@dashed_circle': lambda: dashed_circle(), '@dashed_circle_dot': lambda: dashed_circle(dot=True)}


def path_data(symbol):
    if symbol in CUSTOM:
        return CUSTOM[symbol]()
    file = CACHE / f'{symbol}.svg'
    if not file.exists():
        CACHE.mkdir(parents=True, exist_ok=True)
        url = f'https://cdn.jsdelivr.net/npm/@material-symbols/svg-400@{VERSION}/rounded/{symbol}.svg'
        file.write_bytes(urllib.request.urlopen(url).read())
    paths = re.findall(r'<path d="([^"]+)"', file.read_text())
    if len(paths) != 1:
        raise SystemExit(f'{symbol}: expected one path, found {len(paths)}')
    return paths[0]


def blob(lobes, depth, points=48, radius=380):
    """A closed shape whose radius ripples `lobes` times, as one M...L...Z path."""
    out = []
    for i in range(points):
        a = 2 * math.pi * i / points
        r = radius * (1 - depth + depth * math.cos(lobes * a))
        out.append(f'{480 + r * math.sin(a):.0f} {-480 - r * math.cos(a):.0f}')
    return 'M' + 'L'.join(out) + 'Z'


# Material 3 Expressive loading indicator: the spinner glyph morphs between these shapes.
LOADER_SHAPES = [blob(8, .08), blob(4, .12), blob(5, .07), blob(2, .14), blob(9, .06), blob(3, .1)]


def kebab(name):
    return '-'.join(re.findall(r'[A-Z][a-z]*|[0-9]', name)).lower()


def main():
    rows = [line.split() for line in (HERE / 'map.txt').read_text().splitlines() if line.strip()]
    symbols = sorted({symbol for _, symbol in rows})
    out = [
        '/* oxlint-disable eslint/no-restricted-imports -- Passes every Lucide export through and overrides the mapped ones. */',
        '// Generated by t3code-customize tools/material-icons/generate.py. Do not edit by hand.',
        f'// Path data: Material Symbols Rounded 400 from @material-symbols/svg-400@{VERSION} (Apache-2.0, Google).',
        '// The web build resolves "lucide-react" to this file, so app code keeps its Lucide imports.',
        'import { forwardRef } from "react";',
        'import type { LucideProps } from "lucide-react";',
        '',
        'export * from "lucide-react";',
        '',
        'function symbol(name: string, d: string, morph?: string) {',
        '  const Icon = forwardRef<SVGSVGElement, Omit<LucideProps, "ref">>(function MaterialSymbol(props, ref) {',
        '    const {',
        '      size = 24,',
        '      color = "currentColor",',
        '      className,',
        '      children,',
        '      strokeWidth,',
        '      absoluteStrokeWidth,',
        '      stroke,',
        '      fill,',
        '      ...rest',
        '    } = props;',
        '    // Lucide stroke options have no meaning for filled glyphs.',
        '    void strokeWidth;',
        '    void absoluteStrokeWidth;',
        '    void stroke;',
        '    const labelled =',
        '      children !== undefined ||',
        '      rest["aria-label"] !== undefined ||',
        '      rest["aria-labelledby"] !== undefined ||',
        '      rest.role !== undefined;',
        '    return (',
        '      <svg',
        '        ref={ref}',
        '        xmlns="http://www.w3.org/2000/svg"',
        '        viewBox="0 -960 960 960"',
        '        width={size}',
        '        height={size}',
        '        fill={fill === undefined || fill === "none" ? color : fill}',
        '        aria-hidden={labelled ? undefined : true}',
        '        data-material-symbol=""',
        '        className={`lucide lucide-${name}${className ? ` ${className}` : ""}`}',
        '        {...rest}',
        '      >',
        '        <path d={d}>',
        '          {morph === undefined ? null : (',
        '            <animate',
        '              attributeName="d"',
        '              dur="5s"',
        '              repeatCount="indefinite"',
        '              calcMode="spline"',
        '              keyTimes={LOADER_KEY_TIMES}',
        '              keySplines={LOADER_KEY_SPLINES}',
        '              values={morph}',
        '            />',
        '          )}',
        '        </path>',
        '        {children}',
        '      </svg>',
        '    );',
        '  });',
        '  Icon.displayName = name;',
        '  return Icon;',
        '}',
        '',
        'const paths = {',
    ]
    out += [f'  {symbol.lstrip("@")}: "{path_data(symbol)}",' for symbol in symbols]
    out += ['} as const;', '']
    steps = len(LOADER_SHAPES)
    out += [
        '// The spinner morphs between Material shapes while the app spins it.',
        f'const LOADER_KEY_TIMES = "{";".join(f"{i / steps:.4g}" for i in range(steps + 1))}";',
        f'const LOADER_KEY_SPLINES = "{";".join(["0.4 0 0.2 1"] * steps)}";',
        'const LOADER_SHAPES =',
        f'  "{";".join(LOADER_SHAPES + LOADER_SHAPES[:1])}";',
        '',
    ]
    for lucide, symbol in rows:
        if lucide == 'LoaderCircle':
            first = LOADER_SHAPES[0]
            out.append(f'export const {lucide}Icon = symbol("{kebab(lucide)}", "{first}", LOADER_SHAPES);')
            out.append(f'export const {lucide} = {lucide}Icon;')
            continue
        out.append(f'export const {lucide}Icon = symbol("{kebab(lucide)}", paths.{symbol.lstrip("@")});')
        out.append(f'export const {lucide} = {lucide}Icon;')
    target = Path(sys.argv[1]) / OUT
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text('\n'.join(out) + '\n')
    print(f'{len(rows)} icons, {len(symbols)} symbols -> {target}')


if __name__ == '__main__':
    main()
